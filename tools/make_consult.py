def main():
    zin = zipfile.ZipFile(SRC)
    doc = zin.read('word/document.xml').decode()
    body_start = doc.index('<w:body>') + len('<w:body>')
    sect = re.search(r'<w:sectPr\b.*?</w:sectPr>\s*</w:body>', doc, flags=re.S)
    new = doc[:body_start] + build() + sect.group(0) + doc[sect.end():]
    zout = zipfile.ZipFile(OUT, 'w', zipfile.ZIP_DEFLATED)
    for it in zin.infolist():
        data = new.encode() if it.filename == 'word/document.xml' else zin.read(it.filename)
        zout.writestr(it, data)
    zout.close()
    print('ok', OUT)


if __name__ == '__main__':
    main()
