def item(text_runs):
    return para(text_runs, hanging=True)


def cell(content, w, fill=None, bold=False, sz=20, jc='left'):
    shd = f'<w:shd w:val="clear" w:color="auto" w:fill="{fill}"/>' if fill else ''
    borders = ''.join(f'<w:{s} w:val="single" w:sz="4" w:space="0" w:color="{LINE}"/>' for s in ('top', 'left', 'bottom', 'right'))
    if isinstance(content, str):
        content = [content]
    ps = ''.join(
        f'<w:p><w:pPr><w:keepNext/><w:spacing w:before="40" w:after="40"/><w:jc w:val="{jc}"/></w:pPr>{run(c, b=bold, sz=sz)}</w:p>'
        for c in content)
    return (f'<w:tc><w:tcPr><w:tcW w:w="{w}" w:type="dxa"/><w:tcBorders>{borders}</w:tcBorders>{shd}'
            f'<w:tcMar><w:left w:w="100" w:type="dxa"/><w:right w:w="100" w:type="dxa"/></w:tcMar></w:tcPr>{ps}</w:tc>')


def table(rows, grid):
    g = ''.join(f'<w:gridCol w:w="{x}"/>' for x in grid)
    return (f'<w:tbl><w:tblPr><w:tblW w:w="{sum(grid)}" w:type="dxa"/><w:tblLayout w:type="fixed"/>'
            f'<w:tblLook w:val="0000"/></w:tblPr><w:tblGrid>{g}</w:tblGrid>{"".join(rows)}</w:tbl>')


def row(cells, header=False):
    trpr = '<w:trPr><w:cantSplit/>' + ('<w:tblHeader/>' if header else '') + '</w:trPr>'
    return f'<w:tr>{trpr}{"".join(cells)}</w:tr>'


